"""
Dynamic Knowledge Base Registry with LLM-Generated Book Profiles
=================================================================
Stores persistent book-level profiles alongside the vector DB.
Each book gets: summary, main_topics, key_concepts, and coverage.
Profiles are generated by LLM analysis of representative content
and stored as a JSON file for persistence across restarts.
"""

import json
import os
from pathlib import Path
from typing import Dict, Any, List

from dotenv import load_dotenv
from langchain_openai import ChatOpenAI

from retrieval.vector_store import get_collection, list_knowledge_bases
from settings import ROOT

load_dotenv(ROOT / ".env")

# Persistent profile storage
PROFILES_DIR = ROOT / "kb_profiles"
PROFILES_DIR.mkdir(exist_ok=True)
PROFILES_FILE = PROFILES_DIR / "book_profiles.json"

_REGISTRY_CACHE: Dict[str, Dict[str, Any]] | None = None
_KNOWN_COLLECTIONS: tuple[str, ...] | None = None


def clear_kb_registry_cache():
    """Clear cached KB profiles to force re-discovery on next query."""
    global _REGISTRY_CACHE, _KNOWN_COLLECTIONS
    _REGISTRY_CACHE = None
    _KNOWN_COLLECTIONS = None


def _load_profiles() -> Dict[str, Dict[str, Any]]:
    """Load persisted book profiles from disk."""
    if PROFILES_FILE.exists():
        try:
            with open(PROFILES_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, IOError):
            return {}
    return {}


def _save_profiles(profiles: Dict[str, Dict[str, Any]]) -> None:
    """Persist book profiles to disk."""
    try:
        with open(PROFILES_FILE, "w", encoding="utf-8") as f:
            json.dump(profiles, f, indent=2, ensure_ascii=False)
    except IOError as e:
        print(f"Warning: Could not save KB profiles: {e}")


def _get_profile_llm() -> ChatOpenAI | None:
    """Get LLM client for profile generation."""
    api_key = os.getenv("GE_API_KEY")
    base_url = os.getenv("LLM_BASE_URL")
    model_name = os.getenv("LLM_MODEL")
    if api_key and base_url and model_name:
        return ChatOpenAI(
            model=model_name,
            api_key=api_key,
            base_url=base_url,
            temperature=0.0,
        )
    return None


def _extract_representative_content(kb_name: str, max_samples: int = 15) -> str:
    """
    Extract representative text from across the book for LLM profiling.
    Samples from beginning, middle, and end to capture full scope.
    """
    col = get_collection(kb_name)
    total = col.count()
    if total == 0:
        return ""

    stored = col.get(include=["documents", "metadatas"])
    docs = stored.get("documents", [])
    metas = stored.get("metadatas", [])

    if not docs:
        return ""

    # Sort by page to get ordered content
    indexed = sorted(
        zip(docs, metas),
        key=lambda x: (x[1].get("page_start", 0), x[1].get("line_start", 0)),
    )

    # Sample from beginning, middle, and end of the book
    n = len(indexed)
    sample_indices = set()

    # First few chunks (intro/early content)
    for i in range(min(5, n)):
        sample_indices.add(i)

    # Middle chunks
    mid = n // 2
    for i in range(max(0, mid - 2), min(n, mid + 3)):
        sample_indices.add(i)

    # Late chunks (later content)
    for i in range(max(0, n - 5), n):
        sample_indices.add(i)

    # Additional evenly spaced samples
    if n > max_samples:
        step = n // max_samples
        for i in range(0, n, step):
            sample_indices.add(i)
            if len(sample_indices) >= max_samples:
                break

    sample_indices = sorted(sample_indices)[:max_samples]

    parts = []
    for idx in sample_indices:
        doc, meta = indexed[idx]
        chapter = meta.get("chapter", "")
        section = meta.get("section", "")
        page = meta.get("page_start", "?")
        # Truncate each chunk to ~400 chars to fit within context
        text_preview = doc[:400].strip()
        parts.append(
            f"[Chapter: {chapter} | Section: {section} | Page: {page}]\n{text_preview}"
        )

    return "\n\n---\n\n".join(parts)


def generate_book_profile(
    kb_name: str,
    book_name: str,
    collection_name: str | None = None,
) -> Dict[str, Any] | None:
    """
    Generate an LLM-based book profile from representative content.

    Returns a profile dict with:
        kb_id, kb_name, collection_name, summary, main_topics,
        key_concepts, coverage
    """
    llm = _get_profile_llm()
    if llm is None:
        return _generate_fallback_profile(kb_name, book_name, collection_name)

    representative_content = _extract_representative_content(kb_name)
    if not representative_content:
        return None

    prompt = f"""You are analyzing a book to create a comprehensive content profile.

Book Title: "{book_name}"

Below are representative excerpts sampled from across the entire book (beginning, middle, and end sections):

{representative_content}

Based on these excerpts, generate a detailed content profile. Respond ONLY with valid JSON (no markdown, no code blocks):
{{
    "summary": "A 2-3 sentence overview of what this book is about, its main thesis, and target audience.",
    "main_topics": ["topic1", "topic2", "topic3", "..."],
    "key_concepts": ["concept1", "concept2", "concept3", "..."],
    "coverage": "1-2 sentences describing the subject areas and scope this book covers."
}}

Requirements:
- summary: Capture the book's core message and what makes it unique.
- main_topics: List 5-10 main topics and subtopics the book covers.
- key_concepts: List 5-10 key terms, frameworks, or ideas introduced in the book.
- coverage: Describe the breadth of subjects (e.g., "productivity, psychology, habit formation").
"""

    try:
        response = llm.invoke(prompt)
        raw = response.content.strip()

        # Clean markdown fences
        if raw.startswith("```json"):
            raw = raw[7:]
        elif raw.startswith("```"):
            raw = raw[3:]
        if raw.endswith("```"):
            raw = raw[:-3]
        raw = raw.strip()

        parsed = json.loads(raw)

        profile = {
            "kb_id": kb_name,
            "kb_name": book_name,
            "collection_name": collection_name or kb_name,
            "summary": parsed.get("summary", ""),
            "main_topics": parsed.get("main_topics", []),
            "key_concepts": parsed.get("key_concepts", []),
            "coverage": parsed.get("coverage", ""),
        }

        # Persist immediately
        all_profiles = _load_profiles()
        all_profiles[kb_name] = profile
        _save_profiles(all_profiles)

        return profile

    except Exception as e:
        print(f"Warning: LLM profile generation failed for {book_name}: {e}")
        return _generate_fallback_profile(kb_name, book_name, collection_name)


def _generate_fallback_profile(
    kb_name: str,
    book_name: str,
    collection_name: str | None = None,
) -> Dict[str, Any]:
    """Generate a basic profile from metadata when LLM is unavailable."""
    col = get_collection(kb_name)
    stored = col.get(include=["metadatas"])
    metas = stored.get("metadatas", [])

    chapters = sorted({m.get("chapter", "") for m in metas if m.get("chapter") and m.get("chapter") != "Front matter"})
    sections = sorted({m.get("section", "") for m in metas if m.get("section") and m.get("section") != "Front matter"})

    # Filter boilerplate
    sections = [
        s for s in sections
        if not any(b in s.upper() for b in ["ACKNOWLEDGEMENTS", "ABOUT THE AUTHOR", "BONUS MATERIAL", "ALSO BY"])
    ]

    profile = {
        "kb_id": kb_name,
        "kb_name": book_name,
        "collection_name": collection_name or kb_name,
        "summary": f"Book titled '{book_name}' covering {len(chapters)} chapters.",
        "main_topics": sections[:10],
        "key_concepts": [],
        "coverage": f"Covers chapters: {', '.join(chapters[:8])}.",
    }

    all_profiles = _load_profiles()
    all_profiles[kb_name] = profile
    _save_profiles(all_profiles)

    return profile


def get_kb_registry() -> Dict[str, Dict[str, Any]]:
    """
    Dynamically discover all ingested knowledge bases and return their profiles.
    Merges persisted LLM profiles with live ChromaDB state.
    Automatically generates profiles for any unregistered books.
    """
    global _REGISTRY_CACHE, _KNOWN_COLLECTIONS

    current_kbs = tuple(list_knowledge_bases())

    if _REGISTRY_CACHE is not None and _KNOWN_COLLECTIONS == current_kbs:
        return _REGISTRY_CACHE

    persisted = _load_profiles()
    registry: Dict[str, Dict[str, Any]] = {}

    if not current_kbs:
        _REGISTRY_CACHE = {}
        _KNOWN_COLLECTIONS = current_kbs
        return _REGISTRY_CACHE

    for kb_name in current_kbs:
        try:
            col = get_collection(kb_name)
            count = col.count()
            if count == 0:
                continue

            # Get book title from metadata
            col_meta = getattr(col, "metadata", None) or {}
            book_title = col_meta.get("book")

            if not book_title:
                sample = col.get(limit=5, include=["metadatas"])["metadatas"]
                titles = sorted({m.get("book", "") for m in sample if m.get("book")})
                book_title = titles[0] if titles else kb_name

            # Use persisted profile if available
            if kb_name in persisted:
                profile = persisted[kb_name]
                # Ensure it has current book_title
                profile["kb_name"] = book_title
                profile["total_chunks"] = count
                registry[kb_name] = profile
            else:
                # Generate profile for unregistered book
                profile = generate_book_profile(
                    kb_name=kb_name,
                    book_name=book_title,
                    collection_name=kb_name,
                )
                if profile:
                    profile["total_chunks"] = count
                    registry[kb_name] = profile

        except Exception:
            continue

    _REGISTRY_CACHE = registry
    _KNOWN_COLLECTIONS = current_kbs
    return _REGISTRY_CACHE


def get_all_book_profiles() -> List[Dict[str, Any]]:
    """
    Return all book profiles for use by the semantic router.
    Each profile includes: kb_id, kb_name, collection_name, summary,
    main_topics, key_concepts, coverage.
    """
    registry = get_kb_registry()
    return list(registry.values())


def get_profile_for_kb(kb_id: str) -> Dict[str, Any] | None:
    """Get the profile for a specific KB."""
    registry = get_kb_registry()
    return registry.get(kb_id)


def find_kb_candidates(query_text: str, top_k: int = 5) -> List[Dict[str, Any]]:
    """
    Return all registered book profiles as candidates for routing.
    The LLM router will make the selection decision — not embeddings.
    """
    registry = get_kb_registry()
    if not registry:
        return []

    candidates = []
    for kb_id, data in registry.items():
        candidates.append({
            "kb_id": kb_id,
            "kb_name": data.get("kb_name", kb_id),
            "collection_name": data.get("collection_name", kb_id),
            "summary": data.get("summary", ""),
            "main_topics": data.get("main_topics", []),
            "key_concepts": data.get("key_concepts", []),
            "coverage": data.get("coverage", ""),
            "total_chunks": data.get("total_chunks", 0),
        })

    return candidates[:top_k]
